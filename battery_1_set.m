blk = 'pmsm_with_fuel_cell/Battery1';

% Read nominal values from Battery1 so all strict fade inequalities hold
AH_nom    = str2double(get_param(blk, 'AH'));
R1_nom    = str2double(get_param(blk, 'R1'));
R1_ch_nom = str2double(get_param(blk, 'R1_ch'));
V1_nom    = str2double(get_param(blk, 'V1'));

fadeEnums = enumeration('simscape.enum.battery.prm_fade');
fadeOn = ['simscape.enum.battery.prm_fade.' char(fadeEnums(2))];

set_param(blk, ...
    'prm_fade', fadeOn, ...
    'N_fade', '10000', ...
    'AH_fade', num2str(AH_nom * 0.99), ...
    'R1_fade', num2str(R1_nom * 1.01), ...
    'R1_ch_fade', num2str(R1_ch_nom * 1.01), ...
    'V1_fade', num2str(V1_nom - 1), ...
    'num_cycles_specify', 'on', ...
    'num_cycles_priority', 'High', ...
    'num_cycles', '10', ...
    'v', num2str(V1_nom));

set_param('pmsm_with_fuel_cell/battery input capacitor', 'vc', num2str(V1_nom));
set_param('pmsm_with_fuel_cell/Solver Configuration', 'MaxNonlinIter', '10');
set_param('pmsm_with_fuel_cell/duty cycle sum/Saturation', ...
    'LowerLimit', '0.60', ...
    'UpperLimit', '0.635');